import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { createRepo } from './helpers/repo.js'
import { findGlobalComponents, findTagUses, injectImports, kebab, mergeRefs, templateOnly } from '../src/collect/global-components.js'
import { findKnip } from '../src/collect/knip.js'
import { scan } from '../src/collect/scan.js'
import { resolveConfig } from '../src/core/config.js'

let hasKnip = true
try {
  findKnip()
} catch {
  hasKnip = false
}
const needsKnip = hasKnip ? {} : { skip: '没有安装 knip（code-audit 的可选依赖）' }

const DTS = `/* eslint-disable */
// Generated by unplugin-vue-components
export {}
declare module 'vue' {
  export interface GlobalComponents {
    BasicTable: (typeof import('./components/BasicTable/index.vue'))['default']
    ElButton: (typeof import('element-plus/es'))['ElButton']
    Unused: typeof import('@/components/Unused.vue')['default']
    Gone: (typeof import('./components/Gone.vue'))['default']
  }
}
`

test('findGlobalComponents：读出声明文件里登记的本地组件；第三方、不存在的不算', () => {
  const r = findGlobalComponents({
    files: [
      { path: 'src/components.d.ts', content: DTS },
      { path: 'src/other.d.ts', content: "declare module 'vue' { export interface GlobalComponents { ElX: typeof import('element-plus')['ElX'] } }" },
      { path: 'src/types.ts', content: 'export interface GlobalComponents {}' }
    ],
    sourceSet: new Set(['src/components/BasicTable/index.vue', 'src/components/Unused.vue']),
    aliases: { '@': 'src' }
  })
  assert.deepEqual(r.declarations, ['src/components.d.ts'])
  assert.deepEqual([...r.components], [['BasicTable', 'src/components/BasicTable/index.vue'], ['Unused', 'src/components/Unused.vue']])
})

test('findTagUses：模板里的标签（大驼峰、短横线），记下行号；script 里的、名字更长的、自己用自己不算', () => {
  const page = ['<template>', '  <div>', '    <BasicTable :data="x" />', '    <basic-table/>', '    <BasicTableX />', '  </div>', '</template>', '<script setup>', "const s = '<BasicTable>'", '</script>'].join('\n')
  const self = '<template><BasicTable /></template>'
  const r = findTagUses({
    files: [
      { path: 'src/views/a.vue', content: page },
      { path: 'src/components/BasicTable/index.vue', content: self },
      { path: 'src/x.ts', content: '<BasicTable />' }
    ],
    components: new Map([['BasicTable', 'src/components/BasicTable/index.vue']])
  })
  assert.deepEqual(r.get('src/components/BasicTable/index.vue'), [
    { from: 'src/views/a.vue', line: 3 },
    { from: 'src/views/a.vue', line: 4 }
  ])
})

test('injectImports：补在 <script> 那一行，行号不变；没有 script 的在第一行前面补', (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'code-audit-gc-'))
  t.after(() => rmSync(dir, { recursive: true, force: true }))
  mkdirSync(join(dir, 'src/views'), { recursive: true })
  writeFileSync(join(dir, 'src/views/a.vue'), '<template>\n  <T />\n</template>\n<script setup lang="ts">\nconst x = 1\n</script>\n')
  writeFileSync(join(dir, 'src/views/b.vue'), '<template><T /></template>\n')
  injectImports(
    dir,
    new Map([
      ['src/components/T.vue', [{ from: 'src/views/a.vue', line: 2 }, { from: 'src/views/b.vue', line: 1 }]],
      ['src/views/sub/U.vue', [{ from: 'src/views/a.vue', line: 2 }]]
    ])
  )
  const a = readFileSync(join(dir, 'src/views/a.vue'), 'utf8').split('\n')
  assert.equal(a[3], `<script setup lang="ts">import '../components/T.vue';import './sub/U.vue';`)
  assert.equal(a.length, 7)
  assert.equal(readFileSync(join(dir, 'src/views/b.vue'), 'utf8'), "<script>import '../components/T.vue';</script><template><T /></template>\n")
})

test('templateOnly、kebab、mergeRefs', () => {
  assert.equal(templateOnly('<template>\n<A/>\n</template>\n<script>\nx\n</script>\n<style>\ny\n</style>'), '<template>\n<A/>\n</template>\n\n\n\n\n\n')
  assert.equal(kebab('BasicTable'), 'basic-table')
  assert.equal(kebab('HTMLRender'), 'html-render')
  assert.equal(kebab('Icon3d'), 'icon3d')
  const m = mergeRefs(new Map([['a', [{ from: 'x', line: 2 }]]]), new Map([['a', [{ from: 'x', line: 2 }, { from: 'w', line: 1 }]], ['b', [{ from: 'y', line: 1 }]]]))
  assert.deepEqual(m.get('a'), [{ from: 'w', line: 1 }, { from: 'x', line: 2 }])
  assert.deepEqual(m.get('b'), [{ from: 'y', line: 1 }])
})

test('scan + knip：全局注册的组件，模板里用到的算在用；没人用的、只被没人用的页面用到的列为候选', needsKnip, (t) => {
  const repo = createRepo()
  t.after(() => repo.cleanup())
  repo.write('package.json', '{ "dependencies": { "vue": "^3.4.0" } }')
  // tsconfig 把声明文件列为源文件：knip 会把里面的 typeof import 当成引用
  repo.write('tsconfig.json', JSON.stringify({ compilerOptions: { paths: { '@/*': ['./src/*'] } }, include: ['src/**/*.ts', 'src/**/*.vue', 'src/components.d.ts'] }))
  repo.write('src/main.ts', "import App from './App.vue'\nexport default App\n")
  repo.write('src/App.vue', '<template>\n  <BasicTable />\n</template>\n<script setup lang="ts">\nconst a = 1\n</script>\n')
  repo.write('src/components/BasicTable/index.vue', "<template><div /></template>\n<script setup lang=\"ts\">\nimport { cols } from './cols'\n</script>\n")
  repo.write('src/components/BasicTable/cols.ts', 'export const cols = []\n')
  repo.write('src/components/Unused.vue', '<template><i /></template>\n')
  repo.write('src/components/OnlyInDead.vue', '<template><b /></template>\n')
  repo.write('src/views/Dead.vue', '<template><only-in-dead /></template>\n')
  repo.write(
    'src/components.d.ts',
    "export {}\ndeclare module 'vue' {\n  export interface GlobalComponents {\n" +
      "    BasicTable: (typeof import('./components/BasicTable/index.vue'))['default']\n" +
      "    Unused: (typeof import('./components/Unused.vue'))['default']\n" +
      "    OnlyInDead: (typeof import('./components/OnlyInDead.vue'))['default']\n  }\n}\n"
  )
  repo.commit('init')

  const r = scan({ root: repo.root, project: 'p', config: resolveConfig({ entries: ['src/main.ts'], aliases: { '@': 'src' } }) })
  const by = Object.fromEntries(r.candidates.files.map((f) => [f.file, f]))
  assert.deepEqual(Object.keys(by).sort(), ['src/components/OnlyInDead.vue', 'src/components/Unused.vue', 'src/views/Dead.vue'])
  assert.equal(by['src/components/Unused.vue'].status, 'dead')
  assert.equal(by['src/components/OnlyInDead.vue'].status, 'dead-only-ref')
  assert.deepEqual(by['src/components/OnlyInDead.vue'].refs, [{ from: 'src/views/Dead.vue', line: 1, via: 'static' }])
  assert.deepEqual(r.summary.globalComponents, { declarations: ['src/components.d.ts'], components: 3, used: 2 })
})

test('findTagUses：动态组件写死的名字、resolveComponent 都认；注释里的、名字是变量的、名字更长的不认', () => {
  const comps = new Map([['AppModal', 'src/components/AppModal/index.vue']])
  const seen = (content) => findTagUses({ files: [{ path: 'src/A.vue', content }], components: comps }).size > 0
  for (const yes of [
    '<template><component :is="\'AppModal\'" /></template>',
    '<template><component v-bind:is="\'app-modal\'" /></template>',
    '<template><component is="AppModal" /></template>',
    '<template><tr is="vue:app-modal" /></template>',
    "<template><i /></template><script setup>const c = resolveComponent('AppModal')</script>"
  ]) assert.equal(seen(yes), true, yes)
  for (const no of [
    '<template><!-- <AppModal /> --></template>',
    '<template>\n<!--\n  <app-modal />\n-->\n</template>',
    '<template><component :is="name" /></template>',
    "<template><i /></template><script>// resolveComponent('AppModal')</script>",
    '<template><component is="AppModalX" /></template>',
    '<template><div data-is="AppModal" /></template>'
  ]) assert.equal(seen(no), false, no)
})

test('findTagUses：注释去掉后行号不变；resolveComponent 记脚本里的行号', () => {
  const content = ['<template>', '  <!-- <AppModal /> -->', '  <AppModal />', '</template>', '<script setup>', '// x', "const c = resolveComponent('AppModal')", '</script>'].join('\n')
  const r = findTagUses({ files: [{ path: 'src/A.vue', content }], components: new Map([['AppModal', 'src/M.vue']]) })
  assert.deepEqual(r.get('src/M.vue'), [{ from: 'src/A.vue', line: 3 }, { from: 'src/A.vue', line: 7 }])
})
